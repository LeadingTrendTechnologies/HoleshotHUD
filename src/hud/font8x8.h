inline int glyphAdvancePx(unsigned char c)
{
    if (c == ' ')
    {
        return 4;
    }
    const std::uint8_t* g = glyph8x8(c);
    int maxCol = 0;
    for (int row = 0; row < 8; ++row)
    {
        for (int col = 0; col < 8; ++col)
        {
            if (g[row] & (1u << col))
            {
                if (col > maxCol)
                {
                    maxCol = col;
                }
            }
        }
    }
    return maxCol + 2;
}

inline float measureText(const char* text, float size)
{
    if (!text)
    {
        return 0.0f;
    }
    const float px = size / 8.0f;
    float w = 0.0f;
    for (const char* p = text; *p; ++p)
    {
        w += static_cast<float>(glyphAdvancePx(static_cast<unsigned char>(*p))) * px;
    }
    return w;
}
